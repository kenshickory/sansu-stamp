"""生き物ごとの形・色・骨・しぐさの定義。

座標は「その生き物の足もと中心が原点、+X が前、+Z が上、+Y が左」。
単位はメートルで、実物大に合わせてある。
"""
from sdf import ell, cone, chain, schain, mirror_y

SPECIES = {}


def species(fn):
    SPECIES[fn.__name__] = fn
    return fn


def qleg(B, name, y, pts, col, k=0.06, parent="body", n=3, foot=None):
    """脚1本。pts は上から下へ [(x, z, r), ...]。B に骨(付け根側/先側)を追加する。"""
    mid = len(pts) // 2
    bones = [name + "_up" if i < mid else name + "_lo" for i in range(len(pts) - 1)]
    P = schain([(x, y, z, r) for x, z, r in pts], col, bones, k=k, n=n)
    B[name + "_up"] = ((pts[0][0], y, pts[0][1]), (pts[mid][0], y, pts[mid][1]), parent)
    B[name + "_lo"] = ((pts[mid][0], y, pts[mid][1]), (pts[-1][0], y, pts[-1][1]), name + "_up")
    if foot:
        c, r, fcol = foot
        P.append(ell((c[0], y, c[1]), r, fcol, name + "_lo", k=k * 0.5))
    return P


def legs4(B, front, back, width, col, k=0.06, foot_col=None, foot_r=None, fdx=0.0):
    """前後・左右の4本足をまとめて作る。front/back は pts。"""
    P = []
    for side, s in (("L", 1), ("R", -1)):
        for nm, pts in (("fleg", front), ("bleg", back)):
            foot = None
            if foot_r:
                foot = ((pts[-1][0] + fdx, foot_r[2]), foot_r, foot_col or col)
            P += qleg(B, nm + "_" + side, s * width, pts, col, k=k, foot=foot)
    return P


def common_idle(head=3.0, tail=10.0, ears=0.0):
    d = {
        "head": [("z", head, 8.0, 0.0), ("x", head * 0.5, 6.0, 1.0)],
        "tail1": [("x", tail, 3.0, 0.0)],
        "tail2": [("x", tail * 1.3, 3.0, 0.7)],
    }
    if ears:
        d["ear_L"] = [("x", ears, 2.7, 0.0)]
        d["ear_R"] = [("x", -ears, 3.1, 1.3)]
    return d


